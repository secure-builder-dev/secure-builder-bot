#!/usr/bin/env bash
# legacy-inventory.sh — classify every source file as engine-gated or never-gated.
#
# WHY THIS EXISTS
#   The engine gates stories it dispatches. Most real projects adopt it partway through their life,
#   so a large part of the codebase predates it and has never been read by any gate — and code
#   merged from branches outside the engine lands in the same blind spot. Legacy defects and
#   engine defects then sit side by side, indistinguishable, and neither has an owner.
#
#   This gates nothing. It draws the line, so the un-reviewed surface is a finite list that burns
#   down instead of a fog.
#
# METHOD
#   A file is "gated" if a gate has read it. Two signals, either suffices:
#     1. It was brought into main by a merge commit whose hash — or whose merged tip — appears in a
#        gate-log row (`gate-records/gate-log.md`). That is the epic-gate signal: the log row proves
#        the range was reviewed. `git diff --name-only M^1 M` per first-parent merge.
#     2. (legacy) A commit touching it carries the old per-story prefix — `[AZ-03/impl]`,
#        `[PRE-022/tests]`. Kept so repos that ran the per-story lifecycle keep their history.
#   Anything merged without a gate-log row shows up as never gated — which is the point.
#
#   "Gated once" is not a clean bill of health. It means a gate saw the file at least once.
#
# USAGE   engine/scripts/gate/legacy-inventory.sh [--write]

set -uo pipefail
GATE_LIB="$(cd "$(dirname "$0")/../../../qa/scripts" && pwd)/_lib.sh"
cd "$(git rev-parse --show-toplevel 2>/dev/null || echo .)" || exit 1
# shellcheck source=/dev/null
. "$GATE_LIB"

OUT="gate-records/LEGACY-INVENTORY.md"
WRITE=0; [ "${1:-}" = "--write" ] && WRITE=1
MAP="$(mktemp)"; UNGATED_LIST="$(mktemp)"

# Signal 1 — gate-logged merges. Collect every 7+ hex token from gate-log rows, then walk the
# first-parent merges into the main branch; a merge counts if its own hash, its second parent, or
# any commit in the merged range is in the log.
GATE_LOG="gate-records/gate-log.md"; LOGGED="$(mktemp)"; trap 'rm -f "$MAP" "$UNGATED_LIST" "$LOGGED"' EXIT
[ -f "$GATE_LOG" ] && grep -oE '\b[0-9a-f]{7,40}\b' "$GATE_LOG" | sort -u > "$LOGGED" || : > "$LOGGED"
MAIN_REF="$(git rev-parse --verify -q main >/dev/null 2>&1 && echo main || git rev-parse --abbrev-ref HEAD)"
: > "$MAP"
if [ -s "$LOGGED" ]; then
  git log --first-parent --merges --format='%H %P' "$MAIN_REF" 2>/dev/null | while read -r m p1 p2 _; do
    hit=0
    for h in "$m" "$p2"; do grep -q "^${h:0:7}" "$LOGGED" && hit=1; done
    [ $hit -eq 0 ] && git rev-list "$p1..$m" 2>/dev/null | cut -c1-7 | grep -xF -f "$LOGGED" >/dev/null && hit=1
    [ $hit -eq 1 ] && git diff --name-only "$p1" "$m" 2>/dev/null | awk '{print $0 "\t1"}'
  done >> "$MAP"
fi
# Signal 2 — legacy per-story prefixes. Letter, alphanumerics/hyphens, -<digits>, optional /lane.
git log --format='@@@%s' --name-only 2>/dev/null | awk '
  /^@@@/ { engine = ($0 ~ /^@@@\[[A-Za-z][A-Za-z0-9-]*-[0-9]+(\/[a-z]+)?\]/) ? 1 : 0; next }
  NF && engine { print $0 "\t1" }
' >> "$MAP"
sort -u -o "$MAP" "$MAP"

TOT=0; GATED=0; UNGATED=0
for root in $GATE_SRC_ROOTS; do
  [ -d "$root" ] || continue
  while IFS= read -r f; do
    [ -z "$f" ] && continue
    case "$f" in *"/${GATE_TEST_GLOB##*/}/"*) continue ;; esac
    TOT=$((TOT+1))
    # -x: whole-line match. A substring match would let `backend/src/a.ts` vouch for `src/a.ts`.
    if grep -qxF "$(printf '%s\t1' "$f")" "$MAP" 2>/dev/null; then
      GATED=$((GATED+1))
    else
      UNGATED=$((UNGATED+1))
      first=$(git log --reverse --format='%ad' --date=short -- "$f" 2>/dev/null | head -1)
      printf '| `%s` | %s | UNGATED | |\n' "$f" "${first:-?}" >> "$UNGATED_LIST"
    fi
  done < <(gate_find_src "$root" | sort)
done

PCT=0; [ "$TOT" -gt 0 ] && PCT=$(( GATED * 100 / TOT ))
echo "source files: ${TOT} · engine-gated: ${GATED} (${PCT}%) · never gated: ${UNGATED}"

if [ "$WRITE" -eq 1 ]; then
  mkdir -p "$(dirname "$OUT")"
  {
    echo "# Legacy Inventory"
    echo
    echo "_Generated by \`engine/scripts/gate/legacy-inventory.sh --write\` on $(date -u +%Y-%m-%d)."
    echo "Track: \`${APP_TRACK}\`. Re-run to refresh._"
    echo
    echo "A file is **gated** if it was brought into main by a merge that has a row in"
    echo "\`gate-records/gate-log.md\`, or (legacy) by a commit carrying the old story prefix."
    echo "Everything else predates the engine or arrived ungated, and **has never been read by any gate**."
    echo
    echo "Being gated once is not a clean bill of health — it means a gate saw the file at least once."
    echo
    echo "| metric | count |"
    echo "|---|---|"
    echo "| source files (excl. tests, vendored deps, build output) | ${TOT} |"
    echo "| read by at least one gate | ${GATED} (${PCT}%) |"
    echo "| **never read by any gate** | **${UNGATED}** |"
    echo
    echo "## Never-gated files"
    echo
    echo "Disposition each as a review epic (\`planning/epics/<slug>\`) or \`ACCEPTED-LEGACY\` (accept"
    echo "as-is, with a reason). An empty disposition means nobody has decided yet."
    echo
    echo "| file | first commit | status | disposition |"
    echo "|---|---|---|---|"
    cat "$UNGATED_LIST"
  } > "$OUT"
  echo "wrote ${OUT}"
fi
exit 0
