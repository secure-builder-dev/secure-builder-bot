#!/usr/bin/env bash
# generate-truth.sh — "the truth", generated from code, never hand-written.
#
# WHY THIS EXISTS
#   The plan (PRD, API contract, schema draft) says what we intend to build. It goes stale the
#   moment code lands, and nobody notices because nothing re-reads it. This script derives the
#   two things a plan can be checked against — the route table and the database schema — from
#   the code itself, so drift-report.sh can compare plan to truth mechanically at every epic.
#
# WHAT IT WRITES (only ever into docs/truth/)
#   api.md      web + android: every Express route registered under backend/src, with its mount
#               prefix resolved through app.use()/router.use() and imports where possible
#               (unresolvable prefixes are shown as `<mount?>/path`).
#   app-api.md  android only: every Retrofit annotation and Ktor client call under android/.
#   schema.sql  pg_dump --schema-only when DATABASE_URL is set and pg_dump connects; otherwise
#               the concatenation of backend/migrations/**/*.sql and backend/db/**/*.sql.
#   schema.md   table → columns, derived from schema.sql plus Knex / Prisma / Sequelize sources
#               when present. The header names which source produced it.
#
# USAGE   engine/scripts/docs/generate-truth.sh            (or: make docs)
#         engine/scripts/docs/generate-truth.sh --parse-sql <file>   internal: print the SQL
#               table parser's TSV (table<TAB>columns<TAB>source) for one file; writes nothing.
#         DATABASE_URL=postgres://… engine/scripts/docs/generate-truth.sh   prefer pg_dump
# EXIT    Always 0. This is a generator; it reports what it found and never blocks.

set -uo pipefail
GATE_LIB="$(cd "$(dirname "$0")/../../../qa/scripts" && pwd)/_lib.sh"
SELF="engine/scripts/docs/generate-truth.sh"
cd "$(git rev-parse --show-toplevel 2>/dev/null || echo .)" || exit 0
# shellcheck source=/dev/null
. "$GATE_LIB"

OUT="docs/truth"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
SHA="$(git rev-parse --short HEAD 2>/dev/null || echo no-git)"
DATE="$(date -u +%Y-%m-%d)"
HDR_MD="<!-- generated by ${SELF} @ ${SHA} on ${DATE}; do not edit -->"
HDR_SQL="-- generated by ${SELF} @ ${SHA} on ${DATE}; do not edit"
TAB=$'\t'

# ─────────────────────────────────────────────────────────────────────────────
# SQL table parser — used for pg_dump output, raw migrations and (via --parse-sql) by
# drift-report.sh on the hand-written schema doc. Emits: table<TAB>col:type, col:type<TAB>source
# Handles CREATE TABLE [IF NOT EXISTS] [schema.]name (...), ALTER TABLE name ADD [COLUMN] c t,
# DROP TABLE [IF EXISTS] name. Constraint clauses (PRIMARY KEY, CONSTRAINT, …) are skipped.
# ─────────────────────────────────────────────────────────────────────────────
parse_sql() {   # $1 = file  → TSV on stdout
  awk -v src="$1" '
    function trim(s) { sub(/^[ \t\r\n]+/, "", s); sub(/[ \t\r\n]+$/, "", s); return s }
    function clean_name(n) { gsub(/["`]/, "", n); sub(/^[A-Za-z_][A-Za-z0-9_]*\./, "", n); return tolower(n) }
    function add_col(t, item,   n, ty, parts) {
      item = trim(item); if (item == "") return
      if (toupper(item) ~ /^(CONSTRAINT|PRIMARY|UNIQUE|FOREIGN|CHECK|INDEX|KEY|EXCLUDE|LIKE|PERIOD)[ (]/) return
      gsub(/[ \t]*,[ \t]*/, ",", item); gsub(/\([ \t]*/, "(", item)
      split(item, parts, /[ \t]+/)
      n = clean_name(parts[1]); ty = tolower(parts[2]); if (ty == "") ty = "?"
      if (cols[t] == "") cols[t] = n ":" ty; else if (index("," cols[t] ",", "," n ":") == 0) cols[t] = cols[t] ", " n ":" ty
      if (!(t in seen)) { seen[t] = 1; order[++nt] = t }
    }
    { line = $0; sub(/--.*$/, "", line); buf = buf line "\n" }
    END {
      up = toupper(buf); pos = 1
      while ((i = index(substr(up, pos), "CREATE TABLE")) > 0) {
        p = pos + i - 1 + 12; rest = substr(buf, p)
        if (match(toupper(rest), /^[ \t\n]*IF NOT EXISTS/)) rest = substr(rest, RLENGTH + 1)
        if (!match(rest, /^[ \t\n]*[A-Za-z_"`][A-Za-z0-9_."`]*/)) { pos = p; continue }
        name = clean_name(trim(substr(rest, 1, RLENGTH))); rest = substr(rest, RLENGTH + 1)
        if (!match(rest, /^[ \t\n]*\(/)) { pos = p; continue }
        rest = substr(rest, RLENGTH + 1); depth = 1; item = ""; L = length(rest); k = 1
        while (k <= L && depth > 0) {
          c = substr(rest, k, 1)
          if (c == "(") depth++
          else if (c == ")") { depth--; if (depth == 0) { add_col(name, item); break } }
          if (c == "," && depth == 1) { add_col(name, item); item = "" } else item = item c
          k++
        }
        if (!(name in seen)) { seen[name] = 1; order[++nt] = name; cols[name] = cols[name] "" }
        pos = p + k
      }
      pos = 1
      while ((i = index(substr(up, pos), "ALTER TABLE")) > 0) {
        p = pos + i - 1 + 11; rest = substr(buf, p)
        if (match(toupper(rest), /^[ \t\n]*(ONLY[ \t\n]+)?(IF EXISTS[ \t\n]+)?[A-Z_"`][A-Z0-9_."`]*[ \t\n]+ADD[ \t\n]+(COLUMN[ \t\n]+)?(IF NOT EXISTS[ \t\n]+)?[A-Z_"`][A-Z0-9_"`]*[ \t\n]+[A-Z][A-Z0-9_()]*/)) {
          seg = substr(rest, 1, RLENGTH); n = split(seg, w, /[ \t\n]+/)
          tname = ""; for (j = 1; j <= n; j++) if (toupper(w[j]) == "ADD") { tname = clean_name(w[j-1]); break }
          if (tname != "" && (tname in seen)) add_col(tname, w[n-1] " " w[n])
        }
        pos = p
      }
      pos = 1
      while ((i = index(substr(up, pos), "DROP TABLE")) > 0) {
        p = pos + i - 1 + 10; rest = substr(buf, p)
        if (match(toupper(rest), /^[ \t\n]*(IF EXISTS[ \t\n]+)?[A-Z_"`][A-Z0-9_."`]*/)) {
          seg = trim(substr(rest, 1, RLENGTH)); sub(/^[Ii][Ff] [Ee][Xx][Ii][Ss][Tt][Ss][ \t\n]+/, "", seg)
          dropped[clean_name(seg)] = 1
        }
        pos = p
      }
      for (j = 1; j <= nt; j++) { t = order[j]; if (t in dropped) continue; printf "%s\t%s\t%s\n", t, cols[t], src }
    }' "$1"
}

if [ "${1:-}" = "--parse-sql" ]; then
  [ -f "${2:-}" ] && parse_sql "$2"
  exit 0
fi

mkdir -p "$OUT"
ROUTES=0; TABLES=0; APPCALLS=0; SCHEMA_SRC="static"

# ─────────────────────────────────────────────────────────────────────────────
# 1. api.md — Express routes from backend/src
# ─────────────────────────────────────────────────────────────────────────────
BACKEND_FILES="$TMP/backend-files"
if [ -d backend/src ]; then
  find backend/src \( "${GATE_PRUNE[@]}" \) -prune -o -type f \( -name '*.ts' -o -name '*.js' -o -name '*.mts' -o -name '*.cjs' -o -name '*.mjs' \) -print 2>/dev/null \
    | grep -vE '\.(test|spec)\.[cm]?[jt]s$|/__tests__/|/test/|/tests/' | sort > "$BACKEND_FILES"
else
  : > "$BACKEND_FILES"
fi

IDX="$TMP/idx"; : > "$IDX"      # APP / MOUNT / EXPORT / IMPORT / ROUTE rows, tab-separated
if [ -s "$BACKEND_FILES" ]; then
  while IFS= read -r f; do
    awk -v file="$f" '
      function trim(s) { sub(/^[ \t\r]+/, "", s); sub(/[ \t\r]+$/, "", s); return s }
      function squash(s) { gsub(/[ \t\r\n]+/, " ", s); return trim(s) }
      function strip_comment(s,   q, i, c, out, inq) {   # drop // comments outside strings
        out = ""; inq = ""
        for (i = 1; i <= length(s); i++) {
          c = substr(s, i, 1)
          if (inq != "") { out = out c; if (c == inq && substr(s, i-1, 1) != "\\") inq = ""; continue }
          if (c == "\"" || c == "\x27" || c == "`") { inq = c; out = out c; continue }
          if (c == "/" && substr(s, i+1, 1) == "/") break
          out = out c
        }
        return out
      }
      function paren_delta(s,   i, c, d, inq) {
        d = 0; inq = ""
        for (i = 1; i <= length(s); i++) {
          c = substr(s, i, 1)
          if (inq != "") { if (c == inq && substr(s, i-1, 1) != "\\") inq = ""; continue }
          if (c == "\"" || c == "\x27" || c == "`") { inq = c; continue }
          if (c == "(") d++; else if (c == ")") d--
        }
        return d
      }
      # split the argument list starting at position p (just after the opening paren) into
      # top-level args; returns count, fills ARG[]; sets ARGEND to position of the closing paren
      function split_args(s, p,   i, c, depth, inq, cur, n) {
        depth = 1; inq = ""; cur = ""; n = 0; ARGEND = length(s)
        for (i = p; i <= length(s); i++) {
          c = substr(s, i, 1)
          if (inq != "") { cur = cur c; if (c == inq && substr(s, i-1, 1) != "\\") inq = ""; continue }
          if (c == "\"" || c == "\x27" || c == "`") { inq = c; cur = cur c; continue }
          if (c == "(" || c == "[" || c == "{") depth++
          else if (c == ")" || c == "]" || c == "}") { depth--; if (depth == 0) { ARG[++n] = trim(cur); ARGEND = i; return n } }
          if (c == "," && depth == 1) { ARG[++n] = trim(cur); cur = "" } else cur = cur c
        }
        ARG[++n] = trim(cur); return n
      }
      function is_str(a) { return a ~ /^["\x27`].*["\x27`]$/ }
      function unq(a) { return substr(a, 2, length(a) - 2) }
      function chain_of(n, from,   i, a, out) {
        out = ""
        for (i = from; i <= n; i++) {
          a = ARG[i]; if (a == "") continue
          if (a ~ /=>/ || a ~ /^(async[ \t]+)?function[ \t(]/ || a ~ /^async[ \t]*\(/) a = "(inline)"
          if (length(a) > 48) a = substr(a, 1, 45) "..."
          out = (out == "" ? a : out ", " a)
        }
        return out
      }
      function emit_route(var, method, path, chain, ln) {
        printf "ROUTE\t%s\t%d\t%s\t%s\t%s\t%s\n", file, ln, var, toupper(method), path, chain
      }
      function handle(st, ln,   pos, head, var, method, p, n, path, i, rpath) {
        st = squash(st)
        # .route("/p").get(a).post(b) chains
        if (match(st, /[A-Za-z_$][A-Za-z0-9_$]*\.route[ \t]*\([ \t]*["\x27`][^"\x27`]*["\x27`][ \t]*\)/)) {
          head = substr(st, RSTART, RLENGTH); var = head; sub(/\..*/, "", var)
          rpath = head; sub(/^[^"\x27`]*["\x27`]/, "", rpath); sub(/["\x27`].*$/, "", rpath)
          st = substr(st, RSTART + RLENGTH)
          while (match(st, /\.(get|post|put|patch|delete|all)[ \t]*\(/)) {
            method = substr(st, RSTART + 1, RLENGTH - 1); sub(/[ \t]*\($/, "", method)
            p = RSTART + RLENGTH; n = split_args(st, p)
            emit_route(var, method, rpath, chain_of(n, 1), ln)
            st = substr(st, ARGEND + 1)
          }
          return
        }
        while (match(st, /[A-Za-z_$][A-Za-z0-9_$]*\.(get|post|put|patch|delete|all|use)[ \t]*\(/)) {
          head = substr(st, RSTART, RLENGTH); p = RSTART + RLENGTH
          var = head; sub(/\..*/, "", var)
          method = head; sub(/^[^.]*\./, "", method); sub(/[ \t]*\($/, "", method)
          n = split_args(st, p)
          if (method == "use") {
            path = ""; i = 1
            if (n >= 1 && is_str(ARG[1])) { path = unq(ARG[1]); i = 2 }
            for (; i <= n; i++) if (ARG[i] ~ /^[A-Za-z_$][A-Za-z0-9_$]*$/) printf "MOUNT\t%s\t%s\t%s\t%s\n", file, var, path, ARG[i]
          } else if (n >= 1 && is_str(ARG[1]) && ARG[1] ~ /^["\x27`]\//) {
            # app.get("x") with one arg is a settings getter, not a route — require 2+ args or a leading slash
            emit_route(var, method, unq(ARG[1]), chain_of(n, 2), ln)
          }
          st = substr(st, ARGEND + 1)
        }
      }
      {
        raw = strip_comment($0)
        # ── module graph ──
        if (raw ~ /^[ \t]*import[ \t]/ && raw ~ /from[ \t]*["\x27]/) {
          mod = raw; sub(/^.*from[ \t]*["\x27]/, "", mod); sub(/["\x27].*$/, "", mod)
          spec = raw; sub(/^[ \t]*import[ \t]+/, "", spec); sub(/[ \t]*from[ \t]*["\x27].*$/, "", spec); sub(/^type[ \t]+/, "", spec)
          if (spec ~ /^[A-Za-z_$][A-Za-z0-9_$]*[ \t]*(,|$)/) { d = spec; sub(/[ \t]*,.*$/, "", d); printf "IMPORT\t%s\t%s\tdefault\t%s\n", file, d, mod; sub(/^[^,]*,?/, "", spec) }
          if (match(spec, /\{[^}]*\}/)) {
            inner = substr(spec, RSTART + 1, RLENGTH - 2); k = split(inner, parts, ",")
            for (j = 1; j <= k; j++) { q = trim(parts[j]); if (q == "") continue; sub(/^type[ \t]+/, "", q)
              if (q ~ / as /) { imp = q; sub(/ as .*/, "", imp); loc = q; sub(/.* as /, "", loc) } else { imp = q; loc = q }
              printf "IMPORT\t%s\t%s\t%s\t%s\n", file, trim(loc), trim(imp), mod }
          }
        }
        if (match(raw, /require[ \t]*\([ \t]*["\x27][^"\x27]+["\x27][ \t]*\)/)) {
          mod = substr(raw, RSTART, RLENGTH); sub(/^[^"\x27]*["\x27]/, "", mod); sub(/["\x27].*$/, "", mod)
          lhs = substr(raw, 1, RSTART - 1); sub(/^[ \t]*(const|let|var)[ \t]+/, "", lhs); sub(/[ \t]*=[ \t]*$/, "", lhs); lhs = trim(lhs)
          if (lhs ~ /^[A-Za-z_$][A-Za-z0-9_$]*$/) printf "IMPORT\t%s\t%s\tdefault\t%s\n", file, lhs, mod
          else if (lhs ~ /^\{.*\}$/) { inner = substr(lhs, 2, length(lhs) - 2); k = split(inner, parts, ",")
            for (j = 1; j <= k; j++) { q = trim(parts[j]); if (q == "") continue
              if (q ~ /:/) { imp = q; sub(/[ \t]*:.*/, "", imp); loc = q; sub(/.*:[ \t]*/, "", loc) } else { imp = q; loc = q }
              printf "IMPORT\t%s\t%s\t%s\t%s\n", file, trim(loc), trim(imp), mod } }
        }
        if (match(raw, /^[ \t]*export[ \t]+default[ \t]+[A-Za-z_$][A-Za-z0-9_$]*[ \t]*;?[ \t]*$/)) { d = trim(raw); sub(/^export[ \t]+default[ \t]+/, "", d); sub(/[ \t;]*$/, "", d); printf "EXPORT\t%s\t%s\tdefault\n", file, d }
        if (match(raw, /^[ \t]*export[ \t]+(const|let|var|function|async[ \t]+function|class)[ \t]+[A-Za-z_$][A-Za-z0-9_$]*/)) { d = substr(raw, RSTART, RLENGTH); sub(/^.*[ \t]/, "", d); printf "EXPORT\t%s\t%s\t%s\n", file, d, d }
        if (raw ~ /^[ \t]*export[ \t]*\{[^}]*\}[ \t]*;?[ \t]*$/) { inner = raw; sub(/^[^{]*\{/, "", inner); sub(/\}.*$/, "", inner); k = split(inner, parts, ",")
          for (j = 1; j <= k; j++) { q = trim(parts[j]); if (q == "") continue
            if (q ~ / as /) { loc = q; sub(/ as .*/, "", loc); ex = q; sub(/.* as /, "", ex) } else { loc = q; ex = q }
            printf "EXPORT\t%s\t%s\t%s\n", file, trim(loc), trim(ex) } }
        if (match(raw, /^[ \t]*module\.exports[ \t]*=[ \t]*[A-Za-z_$][A-Za-z0-9_$]*[ \t]*;?[ \t]*$/)) { d = raw; sub(/^.*=[ \t]*/, "", d); sub(/[ \t;]*$/, "", d); printf "EXPORT\t%s\t%s\tdefault\n", file, d }
        if (match(raw, /^[ \t]*(module\.)?exports\.[A-Za-z_$][A-Za-z0-9_$]*[ \t]*=[ \t]*[A-Za-z_$][A-Za-z0-9_$]*[ \t]*;?[ \t]*$/)) { e = raw; sub(/^.*exports\./, "", e); sub(/[ \t]*=.*$/, "", e); d = raw; sub(/^.*=[ \t]*/, "", d); sub(/[ \t;]*$/, "", d); printf "EXPORT\t%s\t%s\t%s\n", file, d, e }
        if (match(raw, /(const|let|var)[ \t]+[A-Za-z_$][A-Za-z0-9_$]*[ \t]*(:[^=]*)?=[ \t]*express[ \t]*\(/)) { d = substr(raw, RSTART, RLENGTH); sub(/^(const|let|var)[ \t]+/, "", d); sub(/[ \t:=].*$/, "", d); printf "APP\t%s\t%s\n", file, d }
        # ── statement accumulation for route registrations ──
        if (buf != "") { buf = buf "\n" raw; depth += paren_delta(raw); lines++
          if (depth <= 0 || lines > 40) { handle(buf, start); buf = ""; depth = 0 }
          next }
        if (raw ~ /[A-Za-z_$][A-Za-z0-9_$]*\.(get|post|put|patch|delete|all|use|route)[ \t]*\(/) {
          depth = paren_delta(raw)
          if (depth <= 0) handle(raw, NR); else { buf = raw; start = NR; lines = 0 }
        }
      }
      END { if (buf != "") handle(buf, start) }
    ' "$f" >> "$IDX"
  done < "$BACKEND_FILES"
fi

# prefix resolution ─────────────────────────────────────────────────────────
mod_matches() {   # $1 = module specifier, $2 = candidate file → 0 if the specifier plausibly names the file
  local m="$1" f="$2" seg base dir
  m="${m%.js}"; m="${m%.ts}"; m="${m%.mjs}"; m="${m%.cjs}"; m="${m%/index}"; m="${m%/}"
  seg="${m##*/}"; base="$(basename "${f%.*}")"; dir="$(basename "$(dirname "$f")")"
  [ "$seg" = "$base" ] && return 0
  [ "$base" = "index" ] && [ "$seg" = "$dir" ] && return 0
  return 1
}

CACHE="$TMP/prefix-cache"; : > "$CACHE"
resolve_prefix() {   # $1 = file, $2 = var, $3 = depth → prints prefix or <mount?>
  local f="$1" v="$2" d="$3" hit m parent pre pp e imp src_local src_file g l r
  hit=$(awk -F'\t' -v k="$f|$v" '$1==k {print $2; found=1; exit} END{if(!found) print "\001"}' "$CACHE")
  if [ "$hit" != $'\001' ]; then printf '%s' "$hit"; return; fi
  r="<mount?>"
  if [ "$d" -le 6 ]; then
    if awk -F'\t' -v f="$f" -v v="$v" '$1=="APP" && $2==f && $3==v {found=1} END{exit !found}' "$IDX"; then
      r=""
    else
      m=$(awk -F'\t' -v f="$f" -v v="$v" '$1=="MOUNT" && $2==f && $5==v {print $3 "\t" $4; exit}' "$IDX")
      if [ -n "$m" ]; then
        parent="${m%%${TAB}*}"; pre="${m#*${TAB}}"
        pp=$(resolve_prefix "$f" "$parent" $((d + 1)))
        case "$pp" in "<mount?>") r="<mount?>${pre}" ;; *) r="${pp}${pre}" ;; esac
      else
        # imported into this file? follow to the defining module
        imp=$(awk -F'\t' -v f="$f" -v v="$v" '$1=="IMPORT" && $2==f && $3==v {print $4 "\t" $5; exit}' "$IDX")
        if [ -n "$imp" ]; then
          e="${imp%%${TAB}*}"; m="${imp#*${TAB}}"
          while IFS= read -r src_file; do
            mod_matches "$m" "$src_file" || continue
            src_local=$(awk -F'\t' -v f="$src_file" -v e="$e" '$1=="EXPORT" && $2==f && $4==e {print $3; exit}' "$IDX")
            [ -n "$src_local" ] || continue
            pp=$(resolve_prefix "$src_file" "$src_local" $((d + 1)))
            [ "$pp" = "<mount?>" ] || { r="$pp"; break; }
          done < "$BACKEND_FILES"
        fi
        if [ "$r" = "<mount?>" ]; then
          # exported from this file? find who imports it and where they mount it
          e=$(awk -F'\t' -v f="$f" -v v="$v" '$1=="EXPORT" && $2==f && $3==v {print $4; exit}' "$IDX")
          if [ -n "$e" ]; then
            while IFS="$TAB" read -r g l m; do
              mod_matches "$m" "$f" || continue
              pp=$(resolve_prefix "$g" "$l" $((d + 1)))
              [ "$pp" = "<mount?>" ] || { r="$pp"; break; }
            done < <(awk -F'\t' -v e="$e" '$1=="IMPORT" && $4==e {print $2 "\t" $3 "\t" $5}' "$IDX")
          fi
        fi
      fi
    fi
  fi
  printf '%s\t%s\n' "$f|$v" "$r" >> "$CACHE"
  printf '%s' "$r"
}

ROUTES_TSV="$TMP/routes.tsv"; : > "$ROUTES_TSV"
if grep -q "^ROUTE${TAB}" "$IDX"; then
  while IFS="$TAB" read -r _ file ln var method path chain; do
    pre=$(resolve_prefix "$file" "$var" 0)
    full="${pre}${path}"
    case "$full" in "<mount?>"*) : ;; *) full="/${full#/}" ;; esac
    full=$(printf '%s' "$full" | sed -E 's#//+#/#g; s#(.)/$#\1#')
    printf '%s\t%s\t%s\t%s:%s\n' "$method" "$full" "${chain:-—}" "$file" "$ln" >> "$ROUTES_TSV"
  done < <(grep "^ROUTE${TAB}" "$IDX")
fi
ROUTES=$(wc -l < "$ROUTES_TSV" | tr -d ' ')

{
  printf '%s\n' "$HDR_MD"
  printf '# API truth — Express routes registered under backend/src\n\n'
  if [ ! -s "$BACKEND_FILES" ]; then
    printf '_no backend source found (backend/src has no .ts/.js files)_\n'
  else
    printf 'Prefixes are resolved through `app.use()` / `router.use()` and import names; `<mount?>` means the router was found but where it is mounted could not be determined statically.\n\n'
    printf '| method | path | handler chain (middleware names in arg order) | file:line |\n|---|---|---|---|\n'
    sort -t "$TAB" -k2,2 -k1,1 "$ROUTES_TSV" | awk -F'\t' '{ gsub(/\|/, "\\|", $3); printf "| %s | `%s` | %s | %s |\n", $1, $2, $3, $4 }'
    printf '\n_%s routes._\n' "$ROUTES"
  fi
} > "$OUT/api.md"

# ─────────────────────────────────────────────────────────────────────────────
# 1b. app-api.md — android only: Retrofit annotations + Ktor client calls
# ─────────────────────────────────────────────────────────────────────────────
if [ "$APP_TRACK" = "android" ]; then
  APP_TSV="$TMP/app.tsv"; : > "$APP_TSV"
  if [ -d android ]; then
    find android \( "${GATE_PRUNE[@]}" \) -prune -o -type f -name '*.kt' -print 2>/dev/null | grep -v '/src/test/' | sort | while IFS= read -r f; do
      awk -v file="$f" '
        function trim(s) { sub(/^[ \t\r]+/, "", s); sub(/[ \t\r]+$/, "", s); return s }
        /^[ \t]*(public |internal |private |abstract |open |data |sealed )*(interface|class|object)[ \t]+[A-Za-z_][A-Za-z0-9_]*/ {
          t = $0; sub(/^[ \t]*(public |internal |private |abstract |open |data |sealed )*(interface|class|object)[ \t]+/, "", t); sub(/[^A-Za-z0-9_].*$/, "", t); owner = t }
        /^[ \t]*(override |suspend |private |internal |public |open |inline |protected )*fun[ \t]/ {
          t = $0; sub(/^.*fun[ \t]+(<[^>]*>[ \t]*)?/, "", t); sub(/[ \t]*\(.*$/, "", t); sub(/^.*\./, "", t); fn = t
          if (pm != "") { printf "%s\t%s\t%s.%s\t%s:%d\n", pm, pp, owner, fn, file, pl; pm = "" } }
        /@(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)[ \t]*\(/ {
          m = $0; sub(/^.*@/, "", m); sub(/[ \t]*\(.*$/, "", m)
          p = $0; sub(/^[^(]*\([ \t]*/, "", p); sub(/[ \t]*\).*$/, "", p); gsub(/"/, "", p)
          pm = m; pp = (p == "" ? "/" : p); pl = NR }
        /@HTTP[ \t]*\(/ {
          m = $0; if (match(m, /method[ \t]*=[ \t]*"[A-Z]+"/)) { m = substr(m, RSTART, RLENGTH); sub(/^[^"]*"/, "", m); gsub(/"/, "", m) } else m = "HTTP"
          p = $0; if (match(p, /path[ \t]*=[ \t]*"[^"]*"/)) { p = substr(p, RSTART, RLENGTH); sub(/^[^"]*"/, "", p); gsub(/"/, "", p) } else p = "?"
          pm = m; pp = p; pl = NR }
        /[A-Za-z_][A-Za-z0-9_]*\.(get|post|put|patch|delete|head|options)[ \t]*\([ \t]*"[^"]*"/ && !/@(GET|POST|PUT|PATCH|DELETE)/ {
          s = $0; match(s, /[A-Za-z_][A-Za-z0-9_]*\.(get|post|put|patch|delete|head|options)[ \t]*\([ \t]*"[^"]*"/)
          s = substr(s, RSTART, RLENGTH); m = s; sub(/^[^.]*\./, "", m); sub(/[ \t]*\(.*$/, "", m)
          p = s; sub(/^[^"]*"/, "", p); sub(/"$/, "", p)
          printf "%s\t%s\t%s.%s\t%s:%d\n", toupper(m), p, owner, fn, file, NR }
      ' "$f"
    done > "$APP_TSV"
  fi
  APPCALLS=$(wc -l < "$APP_TSV" | tr -d ' ')
  {
    printf '%s\n' "$HDR_MD"
    printf '# App API truth — Retrofit interfaces and Ktor client calls under android/\n\n'
    if [ "$APPCALLS" -eq 0 ]; then printf '_no Retrofit/Ktor calls found under android/_\n'; else
      printf '| method | path | interface.function | file:line |\n|---|---|---|---|\n'
      sort -t "$TAB" -k2,2 -k1,1 "$APP_TSV" | awk -F'\t' '{ printf "| %s | `%s` | %s | %s |\n", $1, $2, $3, $4 }'
      printf '\n_%s app calls._\n' "$APPCALLS"
    fi
  } > "$OUT/app-api.md"
fi

# ─────────────────────────────────────────────────────────────────────────────
# 2. schema.sql + schema.md
# ─────────────────────────────────────────────────────────────────────────────
SCHEMA_TSV="$TMP/schema.tsv"; : > "$SCHEMA_TSV"
DUMP="$TMP/schema.sql"; HAVE_SQL=0

if [ -n "${DATABASE_URL:-}" ] && command -v pg_dump >/dev/null 2>&1 \
   && pg_dump --schema-only --no-owner --no-privileges "$DATABASE_URL" > "$DUMP" 2>/dev/null && [ -s "$DUMP" ]; then
  SCHEMA_SRC="pg_dump"; HAVE_SQL=1
  { printf '%s\n' "$HDR_SQL"; cat "$DUMP"; } > "$OUT/schema.sql"
  parse_sql "$OUT/schema.sql" | awk -F'\t' '{ printf "%s\t%s\tpg_dump\n", $1, $2 }' >> "$SCHEMA_TSV"
else
  [ -n "${DATABASE_URL:-}" ] && printf 'note: DATABASE_URL set but pg_dump unavailable or could not connect — falling back to static sources\n' >&2
  SQL_FILES="$TMP/sql-files"
  { [ -d backend/migrations ] && find backend/migrations -type f -name '*.sql'
    [ -d backend/db ] && find backend/db -type f -name '*.sql'; } 2>/dev/null | sort > "$SQL_FILES"
  if [ -s "$SQL_FILES" ]; then
    HAVE_SQL=1
    { printf '%s\n' "$HDR_SQL"
      while IFS= read -r f; do printf -- '\n-- ───── source: %s ─────\n' "$f"; cat "$f"; printf '\n'; done < "$SQL_FILES"
    } > "$OUT/schema.sql"
    while IFS= read -r f; do parse_sql "$f"; done < "$SQL_FILES" >> "$SCHEMA_TSV"
  fi
  # Knex-style TS/JS migrations
  if [ -d backend ]; then
    find backend \( "${GATE_PRUNE[@]}" \) -prune -o -type f \( -name '*.ts' -o -name '*.js' \) \( -path '*migrations*' -o -path '*/db/*' -o -path '*/database/*' \) -print 2>/dev/null \
      | grep -vE '\.(test|spec)\.[jt]s$|/__tests__/' | sort | while IFS= read -r f; do
      awk -v src="$f" '
        /(function|const|let|exports\.)[ \t]*down[ \t]*[(=:]|exports\.down|export (async )?function down/ { exit }
        { line = $0; sub(/\/\/.*$/, "", line)
          if (match(line, /\.(createTable|createTableIfNotExists|alterTable|table)[ \t]*\([ \t]*["\x27`][A-Za-z_][A-Za-z0-9_]*["\x27`]/)) {
            t = substr(line, RSTART, RLENGTH); sub(/^[^"\x27`]*["\x27`]/, "", t); sub(/["\x27`]$/, "", t); cur = tolower(t)
            if (!(cur in seen)) { seen[cur] = 1; order[++n] = cur } }
          if (cur == "") next
          rest = line
          while (match(rest, /(^|[^A-Za-z0-9_.])(t|table|tbl)\.[A-Za-z]+[ \t]*\([ \t]*["\x27`][A-Za-z_][A-Za-z0-9_]*["\x27`]/)) {
            seg = substr(rest, RSTART, RLENGTH); rest = substr(rest, RSTART + RLENGTH)
            ty = seg; sub(/^[^.]*\./, "", ty); sub(/[ \t]*\(.*$/, "", ty)
            c = seg; sub(/^[^"\x27`]*["\x27`]/, "", c); sub(/["\x27`]$/, "", c)
            if (ty ~ /^(foreign|index|unique|primary|dropColumn|dropColumns|dropForeign|dropIndex|dropUnique|dropPrimary|renameColumn|check|comment)$/) continue
            if (ty == "specificType") { if (match(rest, /^[ \t]*,[ \t]*["\x27`][^"\x27`]*["\x27`]/)) { ty = substr(rest, RSTART, RLENGTH); sub(/^[^"\x27`]*["\x27`]/, "", ty); sub(/["\x27`]$/, "", ty) } }
            add(cur, c ":" tolower(ty)) }
          if (line ~ /(^|[^A-Za-z0-9_.])(t|table|tbl)\.timestamps[ \t]*\(/) { add(cur, "created_at:timestamp"); add(cur, "updated_at:timestamp") }
          if (line ~ /(^|[^A-Za-z0-9_.])(t|table|tbl)\.increments[ \t]*\([ \t]*\)/) add(cur, "id:increments")
          if (line ~ /(^|[^A-Za-z0-9_.])(t|table|tbl)\.uuid[ \t]*\([ \t]*\)/) add(cur, "id:uuid")
        }
        function add(t, kv,   k) { k = kv; sub(/:.*/, "", k); if (index("," cols[t] ",", "," k ":") == 0) cols[t] = (cols[t] == "" ? kv : cols[t] ", " kv) }
        END { for (i = 1; i <= n; i++) printf "%s\t%s\t%s\n", order[i], cols[order[i]], src }
      ' "$f"
    done >> "$SCHEMA_TSV"
  fi
  # Prisma
  for pf in prisma/schema.prisma backend/prisma/schema.prisma; do
    [ -f "$pf" ] || continue
    awk -v src="$pf" '
      /^[ \t]*model[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*\{/ { t = $2; cur = t; if (!(cur in seen)) { seen[cur] = 1; order[++n] = cur }; next }
      cur != "" && /^[ \t]*\}/ { if (mapped != "") { cols[mapped] = cols[cur]; order[n] = mapped; delete cols[cur] }; cur = ""; mapped = ""; next }
      cur != "" && /^[ \t]*@@map[ \t]*\(/ { m = $0; sub(/^[^"]*"/, "", m); sub(/".*$/, "", m); mapped = m; next }
      cur != "" && /^[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]+[A-Za-z_][A-Za-z0-9_\[\]?]*/ && !/^[ \t]*@@/ {
        c = $1; ty = $2; if ($0 ~ /@map[ \t]*\(/) { m = $0; sub(/^.*@map[ \t]*\([ \t]*"/, "", m); sub(/".*$/, "", m); c = m }
        cols[cur] = (cols[cur] == "" ? c ":" tolower(ty) : cols[cur] ", " c ":" tolower(ty)) }
      END { for (i = 1; i <= n; i++) printf "%s\t%s\t%s\n", order[i], cols[order[i]], src }
    ' "$pf" >> "$SCHEMA_TSV"
  done
  # Sequelize define()
  if [ -d backend/src ] && grep -rlE '\.define[ \t]*\([ \t]*["\x27][A-Za-z_]' backend/src 2>/dev/null | grep -v node_modules >/dev/null; then
    grep -rlE '\.define[ \t]*\([ \t]*["\x27][A-Za-z_]' backend/src 2>/dev/null | grep -v node_modules | sort | while IFS= read -r f; do
      awk -v src="$f" '
        /\.define[ \t]*\([ \t]*["\x27][A-Za-z_][A-Za-z0-9_]*["\x27]/ { t = $0; sub(/^.*\.define[ \t]*\([ \t]*["\x27]/, "", t); sub(/["\x27].*$/, "", t); cur = tolower(t); if (!(cur in seen)) { seen[cur] = 1; order[++n] = cur }; depth = 0; next }
        cur != "" && /^[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]*:[ \t]*(\{[ \t]*type[ \t]*:[ \t]*)?(DataTypes|Sequelize)\.[A-Za-z_]+/ {
          c = $1; sub(/:$/, "", c); ty = $0; sub(/^.*(DataTypes|Sequelize)\./, "", ty); sub(/[^A-Za-z_].*$/, "", ty)
          cols[cur] = (cols[cur] == "" ? c ":" tolower(ty) : cols[cur] ", " c ":" tolower(ty)) }
        cur != "" && /^[ \t]*\}[ \t]*,[ \t]*\{/ { cur = "" }
        END { for (i = 1; i <= n; i++) printf "%s\t%s\t%s\n", order[i], cols[order[i]], src }
      ' "$f"
    done >> "$SCHEMA_TSV"
  fi
fi
[ "$HAVE_SQL" -eq 1 ] || rm -f "$OUT/schema.sql"

# merge duplicate table rows (same table touched by several files): union columns, list sources
MERGED="$TMP/schema-merged.tsv"
awk -F'\t' '
  { t = $1; if (!(t in seen)) { seen[t] = 1; order[++n] = t }
    k = split($2, cs, /, /); for (i = 1; i <= k; i++) { c = cs[i]; if (c == "") continue; nm = c; sub(/:.*/, "", nm)
      if (index("," names[t] ",", "," nm ",") == 0) { names[t] = (names[t] == "" ? nm : names[t] "," nm); cols[t] = (cols[t] == "" ? c : cols[t] ", " c) } }
    if (index(" " srcs[t] " ", " " $3 " ") == 0) srcs[t] = (srcs[t] == "" ? $3 : srcs[t] " " $3) }
  END { for (i = 1; i <= n; i++) printf "%s\t%s\t%s\n", order[i], cols[order[i]], srcs[order[i]] }
' "$SCHEMA_TSV" | sort -t "$TAB" -k1,1 > "$MERGED"
TABLES=$(wc -l < "$MERGED" | tr -d ' ')

{
  printf '%s\n' "$HDR_MD"
  printf '# Schema truth\n\n'
  case "$SCHEMA_SRC" in
    pg_dump) printf '**Source: pg_dump --schema-only** against `DATABASE_URL` (live database). Full DDL in `schema.sql`.\n\n' ;;
    *)       printf '**Source: static** — raw SQL under `backend/migrations/` and `backend/db/`%s, plus Knex / Prisma / Sequelize definitions where present. No live database was consulted.\n\n' "$( [ "$HAVE_SQL" -eq 1 ] && printf ' (concatenated into `schema.sql`)' )" ;;
  esac
  if [ "$TABLES" -eq 0 ]; then
    printf '_no schema source found_\n'
  else
    printf '| table | columns (name:type) | source file |\n|---|---|---|\n'
    awk -F'\t' '{ printf "| %s | %s | %s |\n", $1, ($2 == "" ? "—" : $2), $3 }' "$MERGED"
    printf '\n_%s tables._\n' "$TABLES"
  fi
} > "$OUT/schema.md"

