[ -s "$BACKEND_FILES" ] || printf 'no backend source found\n'
if [ "$APP_TRACK" = "android" ]; then
  printf 'truth: %s routes, %s tables (source: %s), %s app calls\n' "$ROUTES" "$TABLES" "$SCHEMA_SRC" "$APPCALLS"
else
  printf 'truth: %s routes, %s tables (source: %s)\n' "$ROUTES" "$TABLES" "$SCHEMA_SRC"
fi
exit 0
