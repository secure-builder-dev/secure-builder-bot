"""The refresh: fetch each upstream, compare, regenerate, write the changelog; refuse a catalog that breaks a citation.

Fixtures, never the network: `--offline DIR` reads the upstream files from a directory. The three
committed fixtures under fixtures/ are generated by make-upstream.py from the vendored indexes;
the git-backed upstreams (STIG, NIST publications) are built here in temporary repositories.
"""

from __future__ import annotations

import io
import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest
from smallindex import ROOT, VENDORED, write_indexes

from securebuilderbot_standards.refresh import refuse_broken_citations, refresh

FIXTURES = ROOT / "standards" / "tests" / "fixtures"
UNCHANGED, ADDED, WITHDRAWN = FIXTURES / "upstream-unchanged", FIXTURES / "upstream-added-control", FIXTURES / "upstream-withdrawn-cited"
# docs=None: the tracked documents verify-citations scans. engine/SENTINEL-CHECKLIST.md carries no NIST ids in
# this repository (its items cite through standards/data/controls/CONTROLS-MAPPING.md), so the withdrawn
# fixture takes AC-3, which the mapping and the gate agent cite.


def run(**kw) -> tuple[int, str]:
    out = io.StringIO()
    code = refresh(out=out, **kw)
    return code, out.getvalue()


@pytest.fixture
def copy(tmp_path: Path) -> Path:
    """A private copy of the vendored data directory, plus a changelog beside it, as a refresh writes them."""
    d = tmp_path / "standards"
    shutil.copytree(VENDORED, d / "data" / "controls")
    return d / "data" / "controls"


def changelog(data_dir: Path) -> Path:
    return data_dir.parents[1] / "CHANGELOG.md"


# ── criterion 3 ───────────────────────────────────────────────────────────────────────────────

def test_an_unchanged_upstream_is_nothing_to_do(copy):
    code, out = run(data_dir=copy, offline=UNCHANGED, dry_run=True, docs=None)
    assert code == 0, out
    assert "nothing to do" in out and "CURRENT" in out
    assert "STIG" in out and "not provided" in out  # an upstream absent from the offline directory is said, not skipped silently
    assert not changelog(copy).exists()


def test_an_added_control_is_reported_and_dry_run_writes_nothing(copy):
    before = (copy / "nist-800-53r5-index.json").read_bytes()
    code, out = run(data_dir=copy, offline=ADDED, dry_run=True, docs=None)
    assert code == 3, out
    assert "5.2.0 → 5.2.1" in out and "added: AC-99" in out and "Example Control Added Upstream" in out
    assert (copy / "nist-800-53r5-index.json").read_bytes() == before and not changelog(copy).exists()


def test_an_added_control_regenerates_the_index_and_writes_the_changelog(copy):
    code, out = run(data_dir=copy, offline=ADDED, docs=None, today="2026-11-02")
    assert code == 3, out
    new = json.loads((copy / "nist-800-53r5-index.json").read_text())
    assert new["_catalog_version"] == "5.2.1" and new["controls"]["AC-99"]["t"] == "Example Control Added Upstream"
    assert new["_generator"] == "standards/scripts/build-control-index.py"
    log = changelog(copy).read_text()
    assert "## 2026-11-02 — NIST SP 800-53 Rev 5 catalog 5.2.0 → 5.2.1" in log
    assert "- added: AC-99 (Example Control Added Upstream)" in log
    assert json.loads((copy / "nist-800-53r5-baselines.json").read_text())["_catalog_version"] == "5.2.1"


def test_a_catalog_withdrawing_a_cited_control_is_refused_and_names_the_item(copy):
    before = (copy / "nist-800-53r5-index.json").read_bytes()
    code, out = run(data_dir=copy, offline=WITHDRAWN, docs=None, today="2026-11-02")
    assert code == 1, out
    assert "REFUSED" in out and "incorporated into AC-2" in out
    assert re.search(r"AC-3 withdrawn, incorporated into AC-2: cited at \S+\.md:\d+", out)
    assert (copy / "nist-800-53r5-index.json").read_bytes() == before  # nothing adopted
    log = changelog(copy).read_text()  # the record of the refusal is what the PR carries
    assert "REFUSED" in log and "AC-3" in log


def test_the_cli_runs_the_three_criterion_cases(copy):
    cli = [str(ROOT / "standards" / "run"), "refresh", "--data", str(copy)]
    a = subprocess.run([*cli, "--dry-run", "--offline", str(UNCHANGED)], capture_output=True, text=True, cwd=ROOT)
    assert a.returncode == 0 and "nothing to do" in a.stdout
    b = subprocess.run([*cli, "--dry-run", "--offline", str(ADDED)], capture_output=True, text=True, cwd=ROOT)
    assert b.returncode == 3 and "added: AC-99" in b.stdout
    c = subprocess.run([*cli, "--offline", str(WITHDRAWN)], capture_output=True, text=True, cwd=ROOT)
    assert c.returncode == 1 and "AC-3" in c.stdout


# ── the other upstreams, against the small index set ─────────────────────────────────────────

def small_upstream(tmp_path: Path) -> tuple[Path, Path]:
    """A small data dir and an offline dir regenerating to it, plus git-backed STIG and NIST-pubs checkouts."""
    data = write_indexes(tmp_path / "standards" / "data" / "controls")
    up = tmp_path / "up"
    import importlib.util
    spec = importlib.util.spec_from_file_location("mk", FIXTURES / "make-upstream.py")
    mk = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mk)
    nist = json.loads((data / "nist-800-53r5-index.json").read_text())
    base = json.loads((data / "nist-800-53r5-baselines.json").read_text())
    up.mkdir()
    mk.write_nist(up, nist["controls"], "5.2.0", "2026-05-11T00:00:00.00000-00:00", base)
    mk.write_owasp(up, json.loads((data / "owasp-index.json").read_text()))
    mk.write_masvs(up, json.loads((data / "masvs-index.json").read_text()))
    # STIG: one XCCDF manual per benchmark the small index names
    refs = up / "cac" / "shared" / "references"
    refs.mkdir(parents=True)
    stig = json.loads((data / "stig-index.json").read_text())
    for stem in stig["sources"]:
        rules = "".join(f'<Group id="g"><Rule id="r"><version>{rid}</version><title>{e["t"]}</title></Rule></Group>'
                        for rid, e in stig["rules"].items() if e["s"] == stem)
        (refs / f"{stem}-xccdf-manual.xml").write_text(
            f'<?xml version="1.0"?><Benchmark xmlns="http://checklists.nist.gov/xccdf/1.1" id="b">{rules}</Benchmark>')
    # NIST pubs: a git repository whose bib/ file names encode the publications
    ntp = up / "ntp"
    (ntp / "bib").mkdir(parents=True)
    pubs = json.loads((data / "nist-pubs-index.json").read_text())["pubs"]
    for key, e in pubs.items():
        series, number = key.split(" ", 1)
        for rev in e["revisions"]:
            (ntp / "bib" / f"NIST.{series}.{number}{rev}.ris").write_text("")
        for d in e["drafts"]:
            (ntp / "bib" / f"NIST.{series}.{number}{d}.ris").write_text("")
    for i in range(100):  # the builder refuses a tree with under 100 publications: pad both sides
        (ntp / "bib" / f"NIST.SP.1800-{i}.ris").write_text("")
        pubs[f"SP 1800-{i}"] = {"revisions": [""], "drafts": [], "latest": ""}
    idx = data / "nist-pubs-index.json"
    idx.write_text(json.dumps({**json.loads(idx.read_text()), "pubs": dict(sorted(pubs.items()))}))
    subprocess.run(["git", "-C", str(ntp), "init", "-q"], check=True)
    subprocess.run(["git", "-C", str(ntp), "-c", "user.email=t@t", "-c", "user.name=t", "-c", "commit.gpgsign=false",
                    "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(ntp), "-c", "user.email=t@t", "-c", "user.name=t", "-c", "commit.gpgsign=false",
                    "commit", "-q", "-m", "pubs"], check=True)
    return data, up


def test_every_upstream_in_the_small_set_is_current(tmp_path):
    data, up = small_upstream(tmp_path)
    code, out = run(data_dir=data, offline=up, dry_run=True, docs=[])
    assert code == 0, out
    for name in ("NIST SP 800-53", "baselines", "OWASP", "STIG", "MASVS", "NIST publications"):
        assert name in out


def test_stig_owasp_masvs_and_pubs_changes_are_adopted_and_logged(tmp_path):
    data, up = small_upstream(tmp_path)
    refs = up / "cac" / "shared" / "references"
    (refs / "disa-stig-rhel8-v2r8-xccdf-manual.xml").write_text(
        '<?xml version="1.0"?><Benchmark xmlns="http://checklists.nist.gov/xccdf/1.1" id="b">'
        '<Group id="g"><Rule id="r"><version>RHEL-08-010000</version><title>a</title></Rule></Group>'
        '<Group id="g2"><Rule id="r2"><version>RHEL-08-010001</version><title>new rule</title></Rule></Group></Benchmark>')
    (up / "llm" / "2_0_vulns" / "LLM08_VectorAndEmbeddingWeaknesses.md").unlink()
    (up / "llm" / "2_0_vulns" / "LLM08_SomethingElse.md").write_text("x")
    y = up / "masvs" / "OWASP_MASVS.yaml"
    y.write_text(y.read_text() + "  - id: MASVS-STORAGE-2\n    statement: The app prevents leakage of sensitive data.\n")
    (up / "ntp" / "bib" / "NIST.SP.800-163r2.ris").write_text("")
    subprocess.run(["git", "-C", str(up / "ntp"), "-c", "user.email=t@t", "-c", "user.name=t", "-c", "commit.gpgsign=false",
                    "add", "-A"], check=True)
    subprocess.run(["git", "-C", str(up / "ntp"), "-c", "user.email=t@t", "-c", "user.name=t", "-c", "commit.gpgsign=false",
                    "commit", "-q", "-m", "r2"], check=True)
    code, out = run(data_dir=data, offline=up, docs=[], today="2026-11-02")
    assert code == 3, out
    log = changelog(data).read_text()
    assert "STIG index: +1 rule" in log and "RHEL-08-010001" in log
    assert "OWASP LLM Top 10 2025: LLM08" in log and "Something Else" in log
    assert "MASVS: added MASVS-STORAGE-2" in log
    assert "NIST publications: SP 800-163 latest r1 → r2" in log
    assert "MASVS-STORAGE-2" in json.loads((data / "masvs-index.json").read_text())["controls"]
    assert json.loads((data / "nist-pubs-index.json").read_text())["pubs"]["SP 800-163"]["latest"] == "r2"
    assert "RHEL-08-010001" in json.loads((data / "stig-index.json").read_text())["rules"]


def test_a_baseline_naming_a_control_the_new_catalog_lacks_is_refused(tmp_path):
    data, up = small_upstream(tmp_path)
    p = up / "NIST_SP-800-53_rev5_HIGH-baseline_profile.json"
    doc = json.loads(p.read_text())
    doc["profile"]["imports"][0]["include-controls"][0]["with-ids"].append("zz-99")
    p.write_text(json.dumps(doc))
    code, out = run(data_dir=data, offline=up, docs=[])
    assert code == 2 and "ZZ-99" in out  # the builder spells ids the catalog's way


def test_a_refusal_does_not_hide_the_other_upstreams(tmp_path):
    data, up = small_upstream(tmp_path)
    cat = up / "NIST_SP-800-53_rev5_catalog.json"
    doc = json.loads(cat.read_text())
    for g in doc["catalog"]["groups"]:
        for c in g["controls"]:
            if c["id"] == "ac-3":
                c["props"] = [{"name": "status", "value": "withdrawn"}]
                c["links"] = [{"rel": "incorporated-into", "href": "#ac-2"}]
    doc["catalog"]["metadata"]["version"] = "5.2.1"
    cat.write_text(json.dumps(doc))
    docs = tmp_path / "doc.md"
    docs.write_text("- token gate AC-3\n- already wrong AC-99\n")
    code, out = run(data_dir=data, offline=up, docs=[str(docs)], dry_run=True)
    assert code == 1
    assert f"{docs}:1" in out and "AC-99" not in out.split("REFUSED", 1)[1]  # only what this catalog breaks is the refusal's


