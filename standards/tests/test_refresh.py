def test_refuse_broken_citations_names_only_what_the_new_catalog_breaks(small):
    old = json.loads((small / "nist-800-53r5-index.json").read_text())["controls"]
    new = dict(old)
    new["AC-3"] = {"t": "Access Enforcement", "s": "withdrawn", "into": ["AC-2"]}
    del new["SC-7(3)"]
    docs = {"d.md": "AC-3 and SC-7(3) and AC-99 and AC-2\n"}
    broken = refuse_broken_citations(old, new, docs)
    assert [(b.id, b.path, b.line) for b in broken] == [("AC-3", "d.md", 1), ("SC-7(3)", "d.md", 1)]
    assert "incorporated into AC-2" in broken[0].why and "removed from the catalog" in broken[1].why
    assert refuse_broken_citations(old, old, docs) == []


def test_the_refresh_judges_the_same_documents_from_any_directory(copy, tmp_path, monkeypatch):
    # Gate finding B-01 (standards run 1): run from anywhere but the repository root, the refresh
    # found 0 documents and adopted a catalog that withdraws AC-3, which the docs cite.
    monkeypatch.chdir(tmp_path)
    code, out = run(data_dir=copy, offline=WITHDRAWN, docs=None, today="2026-11-02")
    assert code == 1
    assert re.search(r"AC-3 withdrawn, incorporated into AC-2: cited at \S+\.md:\d+", out)


